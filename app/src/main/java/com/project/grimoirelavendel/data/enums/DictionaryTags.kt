    companion object {
        // Map keyed by the EXACT original key string (case-sensitive)
        private val exactTagMap: Map<String, DictionaryTags> = entries.associateBy { it.key }

        // Lowercase fallback map
        private val lowerTagMap: Map<String, DictionaryTags> = entries.associateBy { it.key.lowercase() }

        fun parseToLabels(
            rawTags: String?,
            allowUnmapped: Boolean = true
        ): List<String> {
            if (rawTags.isNullOrBlank()) return emptyList()

            val tokens = rawTags.split("[,;\\s]+".toRegex()).filter { it.isNotBlank() }

            return tokens.mapNotNull { token ->
                // 1. Try case-sensitive exact match first (preserves 'iK', 'oK', 'R', etc.)
                exactTagMap[token]?.label
                // 2. Try lowercase fallback
                    ?: lowerTagMap[token.lowercase()]?.label
                    // 3. Fallback to token if allowUnmapped is true
                    ?: if (allowUnmapped) token else null
            }
        }
    }
